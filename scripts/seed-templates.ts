// Seeds drop_templates from docs/drop-templates.md (the reviewed source of truth).
// Rerun after editing the doc: `pnpm seed:templates`. It writes
//   lib/mock/drop_templates.json   what the demo reads until M1
//   supabase/seed/drop_templates.sql   an upsert by template id, safe to run again
// and refuses to write anything if a template breaks the rules.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseTemplatesMarkdown, templateProblems, type DropTemplate } from "../lib/templates";

const root = join(__dirname, "..");
const templates = parseTemplatesMarkdown(readFileSync(join(root, "docs/drop-templates.md"), "utf8"));
const problems = templates.flatMap(templateProblems);
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}

writeFileSync(join(root, "lib/mock/drop_templates.json"), JSON.stringify(templates, null, 2) + "\n");

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const row = (t: DropTemplate) =>
  `  (${[
    q(t.id),
    q(t.category),
    q(t.goal),
    q(t.name),
    q(t.why),
    json(t.rewards.map((r) => ({ ...r, min_spend_kobo: r.minSpend === null ? null : r.minSpend * 100 }))),
    t.bounceBack ? json({ ...t.bounceBack, min_spend_kobo: t.bounceBack.minSpend === null ? null : t.bounceBack.minSpend * 100 }) : "null",
    t.validityDays,
    t.validWeekdays ? `'{${t.validWeekdays.join(",")}}'::int[]` : "null",
    t.sort,
    "true",
  ].join(", ")})`;

writeFileSync(
  join(root, "supabase/seed/drop_templates.sql"),
  `-- Generated by scripts/seed-templates.ts from docs/drop-templates.md. Do not edit by hand.
insert into drop_templates (id, category, goal, name, why_line, rewards, bounce_back, default_validity_days, valid_weekdays, sort, active)
values
${templates.map(row).join(",\n")}
on conflict (id) do update set
  category = excluded.category, goal = excluded.goal, name = excluded.name, why_line = excluded.why_line,
  rewards = excluded.rewards, bounce_back = excluded.bounce_back, default_validity_days = excluded.default_validity_days,
  valid_weekdays = excluded.valid_weekdays, sort = excluded.sort, active = excluded.active;
`,
);
console.log(`Seeded ${templates.length} templates.`);
